package notemanager.library
import java.time.LocalDateTime
import java.time.format.DateTimeFormatter

class NoteRepository (
    private val database: Database
){
// Each sql query is loaded using prepared statement which can load dynamic input through placeholders.
// the query is executed on the executeUpdate statement at the bottom of the prepared statement
// unless data is being retrieved, in that case  it.executeQuery().use {resultSet -> is used to return a result set of the
// queried data



    fun insertNote(note: Note) {

     //insert into Main Note Table
       val sql = """
             INSERT INTO notes (title, noteBody, timeCreated, noteType) 
             VALUES (?, ?,?, ?) 
             """

        database.prepareStatement(sql,java.sql.Statement.RETURN_GENERATED_KEYS).use {
            it.setString(1, note.title)
            it.setString(2, note.noteBody)
            it.setString(3, note.createDate)
            it.setString(4, note.noteType)
            it.executeUpdate()
            //Because the ID is generated by the database we have to add the id to the note after its entry is created
            it.generatedKeys.use { keys ->  //gets result set containing the key generated from most recent insert
                if (keys.next()) {
                    note.id = keys.getInt(1)
                }
            }
        }





        when(note){
           is MentalNote -> {
               val sql = """
             INSERT INTO MentalNotes (noteID,emotion)
             VALUES (?, ?)
             """
               database.prepareStatement(sql).use {
                   it.setInt(1, note.id!!)  // !! not null assertion operator
                   it.setString(2, note.emotion)
                   it.executeUpdate()
               }

           }
           is ReminderNote -> {
               val sql = """
                   INSERT INTO ReminderNotes (noteID, deadline)
                   VALUES (?, ?)
               """
               //java.sql.date.valueOf used to convert java date time to sql date time
               database.prepareStatement(sql).use {
                   it.setInt(1, note.id!!)  // !! not null assertion operator
                   it.setString(2, note.deadLine)
                   it.executeUpdate()
               }
           }is GeneralNote -> {
            val sql = """
                   INSERT INTO GeneralNotes (noteID)
                   VALUES (?)
               """
            database.prepareStatement(sql).use {
                it.setInt(1, note.id!!)  // !! not null assertion operaton
                it.executeUpdate()
            }
           }


       }


    }


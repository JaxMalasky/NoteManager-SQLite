    fun updateNote(note: Note) {
        val id = note.id ?: return  //nullable int, will return if null
        val sql = """
                   UPDATE notes SET title = ?, noteBody = ? WHERE noteID  = ?
               """

        database.prepareStatement(sql).use{
            it.setString(1, note.title)
            it.setString(2, note.noteBody)
            it.setInt(3, id)
            it.executeUpdate()
        }

       when(note){
           is MentalNote -> {
               val sql = """
                  UPDATE MentalNotes SET emotion = ? WHERE noteID = ?
               """

               database.prepareStatement(sql).use{
                   it.setString(1, note.emotion)
                   it.setInt(2, id)
                   it.executeUpdate()
               }
           }
           is ReminderNote -> {
               val sql = """
                   UPDATE ReminderNotes SET deadline = ? WHERE noteID = ?
               """

               database.prepareStatement(sql).use{
                   it.setString(1, note.deadLine)
                   it.setInt(2, id)
                   it.executeUpdate()
               }
           }
           is GeneralNote -> {
           return
       }

       }





    }

    // SQL JOIN statment is used to generate a new table to pull all note information for different note type creations
    fun selectNote(id : Int) : Note?{
        val sql = """
            SELECT  
                Notes.noteID,
                Notes.title,
                Notes.noteBody,
                Notes.timeCreated,
                Notes.noteType,
                MentalNotes.emotion,
                ReminderNotes.deadline     
            FROM Notes
            LEFT JOIN MentalNotes 
                ON Notes.noteID = MentalNotes.noteID
            LEFT JOIN ReminderNotes
                ON Notes.noteID = ReminderNotes.noteID
            LEFT JOIN GeneralNotes
                ON Notes.noteID = GeneralNotes.noteID
            WHERE Notes.noteID = ?
        """
        database.prepareStatement(sql).use {
            it.setInt(1, id)
            it.executeQuery().use {resultSet ->
                if (!resultSet.next()) {
                    return null
                }
                val id = resultSet.getInt("noteID")
                val title = resultSet.getString("title")
                val noteBody = resultSet.getString("noteBody")
                val timeCreated = LocalDateTime.parse(resultSet.getString("timeCreated"))
                val noteType = resultSet.getString("noteType")

                when(noteType) {
                    "mental_note" -> {

                        val emotion = resultSet.getString("emotion")

                        val mentalNote = MentalNote(
                            id = id,
                            title = title,
                            noteBody = noteBody,
                            emotion = emotion,
                            createDate = timeCreated.toString()

                        )

                        return mentalNote
                    }
                    "reminder_note" -> {

                        val deadLine = resultSet.getString("deadline")

                        val reminderNote = ReminderNote(
                            id = id,
                            title = title,
                            noteBody = noteBody,
                            deadLine = deadLine,
                            createDate = timeCreated.toString()

                        )
                        return reminderNote
                    }
                    "general_note" -> {

                        val generalNote = GeneralNote(
                            id = id,
                            title = title,
                            noteBody = noteBody,
                            createDate = timeCreated.toString()

                        )
                        return generalNote
                    }
                }


            }
        }
            return null
    }

    //selects notes
    fun selectNotes(): List<Note> {
        val notes = mutableListOf<Note>()
        val sql = """
              SELECT  
                Notes.noteID,
                Notes.title,
                Notes.noteBody,
                Notes.timeCreated,
                Notes.noteType,
                MentalNotes.emotion,
                ReminderNotes.deadline     
            FROM Notes
            LEFT JOIN MentalNotes 
                ON Notes.noteID = MentalNotes.noteID
            LEFT JOIN ReminderNotes
                ON Notes.noteID = ReminderNotes.noteID
            LEFT JOIN GeneralNotes
                ON Notes.noteID = GeneralNotes.noteID
        """
        database.prepareStatement(sql).use {
            it.executeQuery().use {resultSet ->
                while(resultSet.next()) {

                    val noteType = resultSet.getString("noteType")

                    when(noteType) {
                     "mental_note" -> {

                         val id = resultSet.getInt("noteID")
                         val title = resultSet.getString("title")
                         val noteBody = resultSet.getString("noteBody")
                         val timeCreated = LocalDateTime.parse(resultSet.getString("timeCreated"))
                         val emotion = resultSet.getString("emotion")

                         val mentalNote = MentalNote(
                             id = id,
                             title = title,
                             noteBody = noteBody,
                             emotion = emotion,
                             createDate = timeCreated.toString()

                         )

                         notes.add(mentalNote)
                     }
                        "reminder_note" -> {
                            val id = resultSet.getInt("noteID")
                            val title = resultSet.getString("title")
                            val noteBody = resultSet.getString("noteBody")
                            val timeCreated = LocalDateTime.parse(resultSet.getString("timeCreated"))
                            val deadLine = resultSet.getString("deadline")

                            val reminderNote = ReminderNote(
                                id = id,
                                title = title,
                                noteBody = noteBody,
                                deadLine = deadLine,
                                createDate = timeCreated.toString()

                            )
                            notes.add(reminderNote)
                        }
                        "general_note" -> {
                            val id = resultSet.getInt("noteID")
                            val title = resultSet.getString("title")
                            val noteBody = resultSet.getString("noteBody")
                            val timeCreated = LocalDateTime.parse(resultSet.getString("timeCreated"))

                            val generalNote = GeneralNote(
                                id = id,
                                title = title,
                                noteBody = noteBody,
                                createDate = timeCreated.toString()

                            )
                            notes.add(generalNote)
                        }
                    }
                }
            }
        }
        return notes  //return list of notes
    }

